import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDir, "..");
const personalityRoot = join(packageRoot, "personality");
const outputPath = join(packageRoot, "src", "generated", "personalityData.ts");

function walkFiles(rootDir) {
  const entries = readdirSync(rootDir, { withFileTypes: true }).sort((left, right) =>
    left.name.localeCompare(right.name),
  );
  const files = [];
  for (const entry of entries) {
    const absolutePath = join(rootDir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkFiles(absolutePath));
      continue;
    }
    files.push(absolutePath);
  }
  return files;
}

const sourceFiles = Object.fromEntries(
  walkFiles(personalityRoot).map((absolutePath) => {
    const relativePath = relative(personalityRoot, absolutePath).replaceAll("\\", "/");
    const buffer = readFileSync(absolutePath);
    const encoding = relativePath.startsWith("assets/") ? "base64" : "utf8";
    return [
      relativePath,
      {
        encoding,
        content: encoding === "base64" ? buffer.toString("base64") : buffer.toString("utf8"),
      },
    ];
  }),
);

const contentHash = createHash("sha256")
  .update(
    JSON.stringify(
      Object.keys(sourceFiles)
        .sort()
        .map((path) => [path, sourceFiles[path]]),
    ),
  )
  .digest("hex");

const output = `/* This file is generated by scripts/generate-personality-data.mjs. */
export const GENERATED_PERSONALITY_FILES = ${JSON.stringify(sourceFiles, null, 2)} as const;
export const GENERATED_PERSONALITY_CONTENT_HASH = ${JSON.stringify(contentHash)} as const;
`;

writeFileSync(outputPath, output, "utf8");
